		<entry>
		<img class="img-responsive img-rounded" src="images/moons.jpg"/>
		Most unique set of portraits seen at the Vatican Museum: a series of astronomical observations including the position of the moon and planets commissioned in 1711 by the Bolognese Count Luigi Marsili from the painter Donato Creti as a gift for Pope Clement XI, a patron of the arts and sciences. The purpose of these paintings was to convince the Pope of the importance and usefulness for the Church to have an astronomical observatory, which was apparently effective, as shortly thereafter, with Papal support, the first such public observatory in Italy was set up in Bologna.
		</entry>
		
		
